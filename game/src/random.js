// Seeded random numbers for Neon Bay. The whole city, the traffic and every
// staged screenshot scene come from one of these, so ?shot=chase&seed=1 builds
// the exact same streets, cars and cops on every machine that opens it.
export function createRng(seed) {
  let a = (seed >>> 0) || 0x9e3779b9;
  // Warm the state so neighbouring seeds do not produce neighbouring cities.
  for (let i = 0; i < 8; i++) {
    a ^= a << 13; a ^= a >>> 17; a ^= a << 5; a >>>= 0;
  }
  function next() {
    // mulberry32: small, fast, and good enough for a city generator.
    a |= 0; a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  }
  return {
    next,
    range(lo, hi) { return lo + next() * (hi - lo); },
    int(lo, hi) { return Math.floor(lo + next() * (hi - lo + 1)); },
    pick(list) { return list[Math.floor(next() * list.length)]; },
    chance(p) { return next() < p; },
    shuffle(list) {
      for (let i = list.length - 1; i > 0; i--) {
        const j = Math.floor(next() * (i + 1));
        const tmp = list[i]; list[i] = list[j]; list[j] = tmp;
      }
      return list;
    },
    // A stable 32-bit hash of a string, for naming seeds from words.
    hash(str) {
      let h = 2166136261;
      for (let i = 0; i < str.length; i++) {
        h ^= str.charCodeAt(i);
        h = Math.imul(h, 16777619);
      }
      return h >>> 0;
    },
  };
}

// Angle helpers the whole game shares.
export function clamp(v, lo, hi) { return v < lo ? lo : v > hi ? hi : v; }
export function lerp(a, b, t) { return a + (b - a) * t; }
export function dist2(ax, ay, bx, by) {
  const dx = ax - bx, dy = ay - by;
  return dx * dx + dy * dy;
}
export function angleLerp(a, b, t) {
  let d = (b - a) % (Math.PI * 2);
  if (d > Math.PI) d -= Math.PI * 2;
  if (d < -Math.PI) d += Math.PI * 2;
  return a + d * t;
}
export function angleDiff(a, b) {
  let d = (b - a) % (Math.PI * 2);
  if (d > Math.PI) d -= Math.PI * 2;
  if (d < -Math.PI) d += Math.PI * 2;
  return d;
}
